CREATE TABLE IF NOT EXISTS integration_settings (
 id TINYINT PRIMARY KEY,
 location_id VARCHAR(120) NOT NULL,
 token_encrypted TEXT NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL,
 role ENUM('ADMIN','MANAGER','AGENT') NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(200) NOT NULL,
 version INT NOT NULL DEFAULT 1,
 status ENUM('DRAFT','PUBLISHED') NOT NULL DEFAULT 'DRAFT',
 fields JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source_contract_id VARCHAR(120) NOT NULL UNIQUE,
 ghl_contact_id VARCHAR(120),
 client_name VARCHAR(200) NOT NULL,
 category_id BIGINT UNSIGNED,
 requirements_snapshot JSON,
 status VARCHAR(60) NOT NULL DEFAULT 'COLLECTING',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(120) NOT NULL,
 action VARCHAR(100) NOT NULL,
 details JSON NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
